class BoostWorldScript : public WorldScript
{
public:
    BoostWorldScript() : WorldScript("BoostWorldScript", {WORLDHOOK_ON_STARTUP, WORLDHOOK_ON_AFTER_CONFIG_LOAD}) { }

    // Scripts load after the first config read, so startup reads it too.
    void OnStartup() override
    {
        LoadConfig();
        LoadPool();
    }

    void OnAfterConfigLoad(bool /*reload*/) override { LoadConfig(); }

private:
    static void LoadConfig()
    {
        enabled = sConfigMgr->GetOption<bool>("Boost.Enable", true, false);
        individualProgression = sConfigMgr->GetOption<bool>("IndividualProgression.Enable", true, false);
        progressionLimit = sConfigMgr->GetOption<uint8>("IndividualProgression.ProgressionLimit", 0, false);
    }

    static void LoadPool()
    {
        for (uint8 tier = 0; tier < gearPool.size(); ++tier)
        {
            gearPool[tier].clear();
            ammoPool[tier].clear();
        }
        QueryResult result = WorldDatabase.Query("SELECT tier, item FROM solo_wow_boost_pool");
        if (!result)
        {
            LOG_WARN("server.loading", ">> Boost: solo_wow_boost_pool is empty or missing; boosts are unavailable");
            return;
        }
        do
        {
            Field* fields = result->Fetch();
            uint8 const tier = fields[0].Get<uint8>();
            ItemTemplate const* proto = sObjectMgr->GetItemTemplate(fields[1].Get<uint32>());
            if (!proto || tier >= gearPool.size())
                continue;
            (proto->Class == ITEM_CLASS_PROJECTILE ? ammoPool : gearPool)[tier].push_back(proto);
        } while (result->NextRow());
        LOG_INFO("server.loading", ">> Boost: loaded {} vanilla, {} Outland and {} level 80 gear items",
                 gearPool[0].size(), gearPool[1].size(), gearPool[2].size());
    }
};

class BoostPlayerScript : public PlayerScript
{
public:
    BoostPlayerScript() : PlayerScript("BoostPlayerScript", {PLAYERHOOK_ON_GOSSIP_SELECT, PLAYERHOOK_ON_LOGOUT}) { }

    // A boost still waiting on its database check when the player leaves is dropped, so it can be retried.
    void OnPlayerLogout(Player* player) override { Release(player->GetSession()->GetAccountId()); }

    void OnPlayerGossipSelect(Player* player, uint32 menuId, uint32 sender, uint32 action) override
    {
        if (menuId != Boost::MenuId)
            return;
        CloseGossipMenuFor(player);
        Boost::SpecList const specs = Boost::SpecsFor(player->getClass());
        uint8 const kind = uint8(action / Boost::MaxSpecs);
        uint8 const specIndex = uint8(action % Boost::MaxSpecs);
        if (sender != SENDER_SPEC || kind >= Boost::KIND_COUNT || !specs[specIndex].name)
            return;
        if (std::string const reason = Refusal(player); !reason.empty())
        {
            Say(player, reason);
            return;
        }
        uint32 const account = player->GetSession()->GetAccountId();
        {
            std::lock_guard<std::mutex> lock(pendingMutex);
            if (!pending.insert(account).second)
                return;
        }
        uint8 const era = EraOf(player);
        Boost::Spec const spec = specs[specIndex];
        WithBoostUsed(player, era,
                      [account, era, kind, spec](Player* player, bool used)
                      {
                          // Checked again: the player may have moved, levelled or changed era meanwhile.
                          std::string const reason = Refusal(player);
                          if (used)
                              Say(player, std::string("Your account has already used its ") + Boost::EraName(era) +
                                              " boost.");
                          else if (!reason.empty())
                              Say(player, reason);
                          else if (EraOf(player) != era || !Available(player, era, kind))
                              Say(player, "Your progression changed meanwhile; use .boost again.");
                          else
                              DoBoost(player, era, kind, spec);
                          Release(account);
                      });
    }
};

class BoostCommandScript : public CommandScript
{
public:
    BoostCommandScript() : CommandScript("BoostCommandScript") { }

    ChatCommandTable GetCommands() const override
    {
        static ChatCommandTable commandTable = {{"boost", HandleBoostCommand, SEC_PLAYER, Console::No}};
        return commandTable;
    }

    static bool HandleBoostCommand(ChatHandler* handler)
    {
        Player* player = handler->GetPlayer();
        if (std::string const reason = Refusal(player); !reason.empty())
        {
            handler->SendErrorMessage(reason, false);
            return false;
        }
        uint8 const era = EraOf(player);
        WithBoostUsed(player, era,
                      [era](Player* player, bool used)
                      {
                          if (used)
                              Say(player, std::string("Your account has already used its ") + Boost::EraName(era) +
                                              " boost.");
                          else
                              ShowSpecs(player);
                      });
        return true;
    }
};

void AddSC_boost()
{
    new BoostWorldScript();
    new BoostPlayerScript();
    new BoostCommandScript();
}
