enum BoostSender : uint32
{
    SENDER_SPEC = 1
};

uint8 ProgressionStep(Player* player)
{
    uint8 step = 0;
    for (uint8 i = 1; i <= Boost::ProgressionSteps; ++i)
        if (player->GetQuestStatus(Boost::ProgressionQuestBase + i) == QUEST_STATUS_REWARDED)
            step = i;
    return progressionLimit && step > progressionLimit ? progressionLimit : step;
}

uint8 EraOf(Player* player)
{
    return Boost::EraFor(ProgressionStep(player), individualProgression, player->GetSession()->Expansion());
}

// Whether this kind of boost is open to the character now (its era offers it, it's below the level, and the gear
// for it is loaded).
bool Available(Player* player, uint8 era, uint8 kind)
{
    return Boost::CanBoost(player->GetLevel(), player->getClass(), era, kind) &&
           !gearPool[Boost::GearTier(era, kind)].empty();
}

// Why the player can't boost right now, or empty when they can.
std::string Refusal(Player* player)
{
    if (!enabled)
        return "Boosts are turned off on this server.";
    // Bot sessions (random bots and alt bots) have no client socket.
    if (player->GetSession()->IsSocketClosed())
        return "Only players can use a boost.";
    uint8 const era = EraOf(player);
    if (player->getClass() == Boost::ClassDeathKnight)
        return "Death knights can't be boosted.";
    bool eligible = false;
    bool loaded = false;
    for (uint8 kind = 0; kind < Boost::KIND_COUNT; ++kind)
        if (Boost::CanBoost(player->GetLevel(), player->getClass(), era, kind))
        {
            eligible = true;
            loaded = loaded || Available(player, era, kind);
        }
    if (!eligible)
        return "This character is already at or above every boost level open to it.";
    if (!loaded)
        return "Boost gear isn't loaded (the solo_wow_boost_pool table is empty).";
    if (!player->IsAlive() || player->IsInCombat() || player->IsInFlight() || player->InBattleground() ||
        player->InArena() || player->GetMap()->IsDungeon())
        return "Boost from the open world, alive and out of combat.";
    return {};
}

void Say(Player* player, std::string const& message) { ChatHandler(player->GetSession()).SendSysMessage(message); }

// Runs `then` with whether the account has used this era's boost. Game masters may boost again, for testing.
// Skipped when the player has left meanwhile, or relogged onto another character.
void WithBoostUsed(Player* player, uint8 era, std::function<void(Player*, bool)> then)
{
    WorldSession* session = player->GetSession();
    ObjectGuid const guid = player->GetGUID();
    bool const unlimited = session->GetSecurity() >= SEC_GAMEMASTER;
    session->GetQueryProcessor().AddCallback(
        CharacterDatabase
            .AsyncQuery(Acore::StringFormat("SELECT 1 FROM solo_wow_boost WHERE account = {} AND era = {}",
                                            session->GetAccountId(), era))
            .WithCallback(
                [session, guid, unlimited, then = std::move(then)](QueryResult result)
                {
                    Player* player = session->GetPlayer();
                    if (player && player->IsInWorld() && player->GetGUID() == guid)
                        then(player, result && !unlimited);
                }));
}

// Menu actions carry the kind and the spec: kind * MaxSpecs + spec.
void ShowSpecs(Player* player)
{
    uint8 const era = EraOf(player);
    ClearGossipMenuFor(player);
    Boost::SpecList const specs = Boost::SpecsFor(player->getClass());
    for (uint8 kind = 0; kind < Boost::KIND_COUNT; ++kind)
    {
        if (!Available(player, era, kind))
            continue;
        std::string const level = std::to_string(Boost::BoostLevel(era, kind));
        Boost::Spot const spot = Boost::Landing(era, player->GetTeamId() == TEAM_HORDE, kind);
        for (uint8 i = 0; i < Boost::MaxSpecs; ++i)
            if (specs[i].name)
                AddGossipItemFor(player, GOSSIP_ICON_BATTLE, "Boost to level " + level + " as " + specs[i].name,
                                 SENDER_SPEC, kind * Boost::MaxSpecs + i,
                                 "Boost " + player->GetName() + " to level " + level + " as " + specs[i].name +
                                     " and travel to " + spot.name + "? This uses your account's " +
                                     Boost::EraName(era) + " boost and can't be undone.",
                                 0, false);
    }
    player->PlayerTalkClass->GetGossipMenu().SetMenuId(Boost::MenuId);
    SendGossipMenuFor(player, DEFAULT_GOSSIP_MESSAGE, player->GetGUID());
}

// Every class spell the level allows: trainer spells (repeated while a learn opens up more) and spells
// rewarded by class quests, such as pets, forms and totems.
void LearnClassSpells(Player* player, uint8 level)
{
    std::vector<Trainer::Trainer const*> const& trainers = sObjectMgr->GetClassTrainers(player->getClass());
    bool learned;
    do
    {
        learned = false;
        for (Trainer::Trainer const* trainer : trainers)
        {
            if (!trainer->IsTrainerValidForPlayer(player))
                continue;
            for (Trainer::Spell const& spell : trainer->GetSpells())
            {
                if (!trainer->CanTeachSpell(player, &spell))
                    continue;
                if (spell.IsCastable())
                    player->CastSpell(player, spell.SpellId, true);
                else
                    player->learnSpell(spell.SpellId, false);
                if (!trainer->CanTeachSpell(player, &spell))
                    learned = true;
            }
        }
    } while (learned);

    for (auto const& [questId, quest] : sObjectMgr->GetQuestTemplates())
        if (quest->GetRequiredClasses() && quest->GetMinLevel() <= level && player->SatisfyQuestClass(quest, false) &&
            player->SatisfyQuestRace(quest, false))
            player->learnQuestRewardedSpells(quest);
}

