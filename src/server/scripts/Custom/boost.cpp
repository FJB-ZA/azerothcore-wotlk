// Read once per config load. IndividualProgression.* belong to mod-individual-progression and are read
// with its defaults.
bool enabled = true;
bool individualProgression = true;
uint8 progressionLimit = 0;

std::array<std::vector<ItemTemplate const*>, 3> gearPool;
std::array<std::vector<ItemTemplate const*>, 3> ammoPool;

// Accounts with a boost between the menu choice and the database check, so two clicks cannot boost twice.
